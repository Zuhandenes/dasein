/**
 * Услуги. Короткое описание — для карточек на главной,
 * `detail` — для страницы /services.
 *
 * priceRub и durationMin используются бэкендом (сумма к оплате, длина слота),
 * держите их в согласии с текстом в `priceLabel` / `formatLabel`.
 */

export type ServiceDetailSection = {
  heading: string;
  /** Абзацы текста */
  body?: string[];
  /** Маркированный список */
  bullets?: string[];
  /** Таблица-сравнение (2 колонки) */
  table?: { columns: [string, string]; rows: [string, string][] };
};

export type Service = {
  slug: string;
  name: string;
  /** 1–2 фразы для карточки */
  summary: string;
  priceRub: number;
  /** Как цена показывается людям */
  priceLabel: string;
  durationMin: number;
  formatLabel: string;
  /** Кому подойдёт — для карточки */
  audience: string[];
  /** Можно ли записаться через календарь на сайте */
  bookable: boolean;
  /** Тип: разовая сессия или пакет */
  kind: "single" | "package";
  /** Запасная платёжная ссылка (режим PAYMENT_MODE=manual или Taplink) */
  paymentUrlFallback?: string;
  /** Развёрнутое описание для /services */
  detail: {
    lead: string;
    sections: ServiceDetailSection[];
  };
};

